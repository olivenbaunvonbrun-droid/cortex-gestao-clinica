export type RegistroAnalysisField = keyof typeof REGISTRO_FIELD_GUIDANCE;

export function registroFieldInstruction(field: string): string {
  if (!Object.prototype.hasOwnProperty.call(REGISTRO_FIELD_GUIDANCE, field)) {
    throw new Error(`Campo de análise não reconhecido: ${field}`);
  }
  return `${REGISTRO_TCC4_FRAMEWORK}\nCAMPO ${field}:\n${REGISTRO_FIELD_GUIDANCE[field as RegistroAnalysisField]}`;
}

export function registroAllFieldsInstruction(): string {
  return `${REGISTRO_TCC4_FRAMEWORK}\nORIENTAÇÕES POR CAMPO:\n${Object.entries(REGISTRO_FIELD_GUIDANCE)
    .map(([field, instruction]) => `${field}: ${instruction}`).join('\n')}`;
}
